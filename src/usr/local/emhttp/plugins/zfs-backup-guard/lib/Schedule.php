<?php
declare(strict_types=1);

namespace ZBG;

/** Unraid reads plugin .cron fragments when update_cron rebuilds root's crontab. */
final class Schedule
{
    private const FILE = 'zfs-backup-guard.cron';
    private const CONFIG = '/boot/config/plugins/zfs-backup-guard';

    public static function sync(): void
    {
        JobStore::synchronized(static function (): void {
            $cli = realpath(__DIR__ . '/../bin/zbg');
            if ($cli === false || strpbrk($cli, "\r\n\0") !== false) {
                throw new \RuntimeException('Absoluter CLI-Pfad für den Zeitplan fehlt oder ist ungültig');
            }
            $lines = ['# Generated by ZFS Backup Guard; edit jobs through the plugin.'];
            foreach (JobStore::all() as $job) {
                if (!$job['enabled']) {
                    continue;
                }
                $id = (string)$job['id'];
                $expression = (string)$job['schedule'];
                if (!preg_match('~^[a-z0-9][a-z0-9-]{0,39}$~', $id) || !Cron::valid($expression)) {
                    throw new \RuntimeException("Ungültiger Zeitplan für Job $id");
                }
                // Canonical whitespace removes embedded newlines accepted by the parser.
                $expression = implode(' ', preg_split('~\s+~', trim($expression)));
                $lines[] = $expression . ' ' . self::command($cli, ['run', $id, '--scheduled']);
            }
            $lines[] = '0 * * * * ' . self::command($cli, ['check-age']);
            self::replace(implode("\n", $lines) . "\n");
        });
    }

    public static function remove(): void
    {
        JobStore::synchronized(static function (): void {
            self::replace(null);
        });
    }

    private static function command(string $cli, array $arguments): string
    {
        $command = implode(' ', array_map('escapeshellarg', array_merge(['/usr/bin/php', $cli], $arguments)));
        // Cron treats percent as stdin/newline even inside shell quotes.
        return str_replace('%', '\\%', $command) . ' >/dev/null 2>&1';
    }

    /** Restore the previous fragment and reload it if activation fails. */
    private static function replace(?string $contents): void
    {
        $file = JobStore::file(self::FILE);
        $previous = is_file($file) ? file_get_contents($file) : null;
        if ($previous === false) {
            throw new \RuntimeException('Vorheriger Zeitplan kann nicht gelesen werden');
        }
        try {
            self::persist($contents);
            self::activate();
        } catch (\Throwable $failure) {
            try {
                self::persist($previous);
                self::activate();
            } catch (\Throwable $rollback) {
                throw new \RuntimeException('Zeitplan-Aktivierung fehlgeschlagen: ' . $failure->getMessage()
                    . '; alter Zeitplan konnte nicht aktiviert werden: ' . $rollback->getMessage(), 0, $failure);
            }
            throw new \RuntimeException('Zeitplan-Änderung zurückgenommen: ' . $failure->getMessage(), 0, $failure);
        }
    }

    private static function persist(?string $contents): void
    {
        if ($contents !== null) {
            JobStore::atomicWrite(self::FILE, $contents);
            return;
        }
        $file = JobStore::file(self::FILE);
        if (file_exists($file) && !unlink($file)) {
            throw new \RuntimeException('Cron-Datei kann nicht entfernt werden');
        }
        JobStore::syncDirectory();
    }

    private static function activate(): void
    {
        // An alternate test configuration can never reload the host's real crontab.
        if (PHP_OS_FAMILY !== 'Linux' || !is_file('/etc/unraid-version')
            || realpath(configDir()) !== self::CONFIG) {
            return;
        }
        $command = '/usr/local/sbin/update_cron';
        if (!is_executable($command)) {
            throw new \RuntimeException('Unraid update_cron fehlt oder ist nicht ausführbar');
        }
        Exec::ok([$command]);
    }
}
